import { expect, test } from '@playwright/test'

test('wide details preserve drafts across resizing and guard book switches', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1180, height: 820 })
  await page.route('https://openlibrary.org/**', (route) => route.abort())
  await page.route('https://covers.openlibrary.org/**', (route) => route.abort())
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Books & imports', exact: true }).click()
  await page.locator('.goodreads-migration__picker input').setInputFiles({
    name: 'responsive.csv', mimeType: 'text/csv', buffer: Buffer.from('Book Id,Title,Author,Exclusive Shelf,Date Added\n1,First story,First Author,to-read,2026/01/01\n2,Second story,Second Author,to-read,2026/01/01'),
  })
  await page.locator('.import-book-expand').first().click()
  await expect(page.locator('.import-book-details')).toBeVisible()
  const rowBox = await page.locator('.import-book-line').first().boundingBox()
  const detailBox = await page.locator('.import-book-details').boundingBox()
  expect(detailBox!.x).toBeGreaterThan(rowBox!.x + rowBox!.width)
  await page.getByRole('checkbox', { name: 'Include Second story' }).uncheck()
  await page.setViewportSize({ width: 430, height: 820 })
  await expect(page.getByRole('checkbox', { name: 'Include Second story' })).not.toBeChecked()
  await expect(page.locator('.import-book-details')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Include Second story' }).check()
  await page.getByRole('button', { name: 'Import 2 books', exact: true }).click()
  await page.getByRole('button', { name: 'View library', exact: true }).last().click()
  await page.setViewportSize({ width: 1180, height: 820 })
  await page.locator('.book-identity').filter({ hasText: 'First story' }).click()
  const detail = page.getByRole('dialog', { name: 'Book details', exact: true })
  await expect(detail).not.toHaveAttribute('aria-modal', 'true')
  await expect(page.locator('.app-content')).not.toHaveAttribute('inert')
  await detail.locator('summary').filter({ hasText: 'Book information' }).click()
  await detail.getByRole('button', { name: /Edit/ }).click()
  await detail.getByRole('textbox', { name: 'Title', exact: true }).fill('First story edited')
  await page.setViewportSize({ width: 430, height: 820 })
  await expect(detail).toHaveAttribute('aria-modal', 'true')
  await expect(detail.getByRole('textbox', { name: 'Title', exact: true })).toHaveValue('First story edited')
  await page.setViewportSize({ width: 1180, height: 820 })
  await page.locator('.book-identity').filter({ hasText: 'Second story' }).click()
  const guard = page.getByRole('dialog', { name: 'Save your changes?' })
  await expect(guard).toBeVisible()
  await guard.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(detail.getByRole('textbox', { name: 'Title', exact: true })).toHaveValue('First story edited')
  await page.locator('.book-identity').filter({ hasText: 'Second story' }).click()
  await guard.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(detail.getByRole('heading', { name: 'Second story', exact: true })).toBeVisible()
  await expect(page.locator('.book-identity').filter({ hasText: 'First story edited' })).toBeVisible()
  await detail.locator('summary').filter({ hasText: 'Book information' }).click()
  await detail.getByRole('button', { name: /Edit/ }).click()
  await detail.getByRole('textbox', { name: 'Title', exact: true }).fill('Discard this title')
  await page.locator('.book-identity').filter({ hasText: 'First story edited' }).click()
  await guard.getByRole('button', { name: 'Discard', exact: true }).click()
  await expect(detail.getByRole('heading', { name: 'First story edited', exact: true })).toBeVisible()
  await expect(page.locator('.book-identity').filter({ hasText: 'Second story' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('wide-library-details.png') })
  await page.setViewportSize({ width: 980, height: 820 })
  await page.evaluate(() => { document.documentElement.dataset.typeScale = 'x-large' })
  await expect(detail).toHaveAttribute('aria-modal', 'true')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => { document.documentElement.dataset.typeScale = 'standard' })
  await page.setViewportSize({ width: 956, height: 440 })
  await expect(detail).toHaveAttribute('aria-modal', 'true')
  await detail.getByRole('button', { name: 'Close', exact: true }).click()
  expect(errors).toEqual([])
})

test('wide search selection and manual drafts survive resizing', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1180, height: 820 })
  await page.route('https://openlibrary.org/search.json**', (route) => route.fulfill({
    contentType: 'application/json', body: JSON.stringify({ docs: [{ key: '/works/OL15297W', title: 'Invisible Cities', author_name: ['Italo Calvino'], editions: { docs: [{ key: '/books/OL26350002M', title: 'Invisible Cities', isbn: ['9780156453806'], language: ['eng'], number_of_pages: 176 }] } }] }),
  }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Add Book', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search Open Library' }).fill('Invisible Cities')
  await page.getByRole('button', { name: 'Inspect book', exact: true }).click()
  await expect(page.locator('.search-selection')).toContainText('176 pages')
  await page.screenshot({ path: testInfo.outputPath('wide-search.png') })
  await page.setViewportSize({ width: 430, height: 820 })
  await expect(page.locator('.search-selection')).toBeHidden()
  await expect(page.getByRole('searchbox', { name: 'Search Open Library' })).toHaveValue('Invisible Cities')
  await page.setViewportSize({ width: 1180, height: 820 })
  await expect(page.locator('.search-selection')).toContainText('Invisible Cities')
  await page.getByRole('button', { name: /Can't find/ }).click()
  await page.getByRole('textbox', { name: 'Book title', exact: true }).fill('My reading notebook')
  await page.setViewportSize({ width: 430, height: 820 })
  await expect(page.getByRole('textbox', { name: 'Book title', exact: true })).toHaveValue('My reading notebook')
})

test('settings categories adapt without losing advanced form state', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1180, height: 820 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Appearance', exact: true })).toBeVisible()
  await expect(page.locator('.goodreads-migration')).toBeHidden()
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  await expect(page.locator('.settings-advanced')).toHaveAttribute('open')
  await page.screenshot({ path: testInfo.outputPath('wide-settings.png') })
  await page.setViewportSize({ width: 430, height: 820 })
  await expect(page.locator('.settings-category-nav')).toBeHidden()
  await expect(page.locator('.goodreads-migration')).toBeVisible()
  await page.setViewportSize({ width: 1180, height: 820 })
  await expect(page.getByRole('button', { name: 'Advanced', exact: true })).toHaveAttribute('aria-current', 'page')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
