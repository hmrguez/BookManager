import { expect, test } from '@playwright/test'

test('settings keep daily controls visible and disclose services and maintenance', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Appearance', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '125%', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Paper fiber' })).toBeHidden()
  await expect(page.locator('.epub-storage-card')).toBeHidden()
  await expect(page.locator('.goodreads-migration')).not.toHaveAttribute('open')
  await page.screenshot({ path: testInfo.outputPath('settings-mobile.png'), fullPage: true })
  await page.getByText('More appearance options', { exact: true }).click()
  await page.getByRole('button', { name: 'Paper fiber' }).click()
  await expect(page.getByRole('button', { name: 'Paper fiber' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: 'Libby Books and reading progress' }).click()
  await expect(page.getByRole('dialog', { name: 'Libby', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.locator('.libby-entry')).toBeFocused()
  await page.locator('.goodreads-migration > summary').click()
  await expect(page.getByRole('button', { name: 'Open Goodreads export' })).toBeVisible()
  for (const img of await page.locator('.settings-service__mark img').all()) {
    expect(await img.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0)).toBe(true)
  }
  await page.setViewportSize({ width: 1180, height: 820 })
  await page.getByRole('button', { name: 'Books & imports', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Appearance', exact: true })).toBeHidden()
  await expect(page.getByRole('button', { name: 'Open Goodreads export' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('settings-services.png'), fullPage: true })
  await page.getByRole('button', { name: 'Advanced', exact: true }).click()
  await expect(page.locator('.epub-storage-card')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => { document.documentElement.dataset.typeScale = 'x-large'; document.documentElement.dataset.paperMode = 'night' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('settings-night-large-text.png'), fullPage: true })
  expect(errors).toEqual([])
})
