import { expect, test } from '@playwright/test'
import { PDFDocument } from 'pdf-lib'

test('one source at a time, with progressive disclosure and persisted attachments', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'My Books', exact: true })).toBeVisible()
  await page.evaluate(async () => {
    const path = '/src/storage/runtime.ts'
    const runtime = await (await import(/* @vite-ignore */ path)).getStorageRuntime()
    const at = new Date().toISOString()
    // A format label alone must never advertise an attached, readable book.
    await runtime.library.save({ id: 'book:source', title: 'The Tainted Cup', authors: ['Robert Jackson Bennett'], format: 'EPUB',
      shelf: 'reading', progress: 42, currentPage: 180, pageCount: 432, rating: 0, notes: '', addedAt: at, lastUpdatedAt: at })
  })
  await page.reload()
  await page.getByRole('button', { name: /The Tainted Cup/ }).first().click()
  const source = page.getByRole('region', { name: 'Reading source' })
  await expect(source.getByRole('button', { name: /^Attach to:/ })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Organize book' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reading', exact: true }).last()).toBeVisible()
  await source.getByRole('button', { name: /^Attach to:/ }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(source.getByRole('menuitemradio', { name: /E-reader/ })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(source.getByRole('menuitemradio', { name: /Audiobook/ })).toBeFocused()
  await page.screenshot({ path: testInfo.outputPath('source-menu-mobile.png') })
  await page.keyboard.press('Escape')
  await expect(source.getByRole('button', { name: /^Attach to:/ })).toBeFocused()
  await expect(page.getByRole('dialog', { name: 'Book details', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('unattached-mobile.png') })
  await expect(source.getByRole('button', { name: 'Continue reading' })).toHaveCount(0)
  await expect(page.locator('.libby-book-link')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit details' })).toBeHidden()
  await page.locator('.book-disclosure > summary').filter({ hasText: 'Book information' }).click()
  await page.getByRole('button', { name: 'Edit details' }).click()
  await page.getByLabel('Title', { exact: true }).fill('The Tainted Cup')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.locator('.book-disclosure > summary').filter({ hasText: 'Book information' }).click()
  await page.locator('.book-notes > summary').click()
  await page.getByLabel('Private note').fill('Return to chapter twelve.')
  await page.locator('.book-notes > summary').click()

  // Closed disclosures must not strand keyboard focus on their hidden controls.
  await page.locator('.book-disclosure > summary').filter({ hasText: 'More options' }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.locator('.book-disclosure > summary').filter({ hasText: 'More options' })).toBeFocused()

  await source.getByLabel('Choose book file').setInputFiles({ name: 'broken.pdf', mimeType: 'application/pdf', buffer: Buffer.from('invalid pdf') })
  await expect(source.getByRole('alert')).toBeVisible()
  await expect(source.getByRole('button', { name: /^Attach to:/ })).toBeEnabled()
  const pdf = await PDFDocument.create()
  pdf.addPage().drawText('A reading fixture')
  await source.getByLabel('Choose book file').setInputFiles({ name: 'reader.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) })
  await expect(source.getByRole('button', { name: 'Continue reading' })).toBeVisible()
  await expect(source.getByRole('button', { name: /^Attach to:/ })).toHaveCount(0)
  await expect(source.getByRole('button', { name: 'Continue reading' })).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('ebook-mobile.png') })

  await source.getByRole('button', { name: 'Change', exact: true }).click()
  await source.getByRole('button', { name: /^Attach to:/ }).click()
  await source.getByRole('menuitemradio', { name: /Audiobook/ }).click()
  await expect(source.getByLabel('Choose book file')).toHaveCount(0)
  const frames = Buffer.alloc(417 * 40)
  for (let i = 0; i < 40; i++) frames.set([0xff, 0xfb, 0x90, 0x64], i * 417)
  await source.getByLabel('Choose audio files').setInputFiles({ name: 'chapter.mp3', mimeType: 'audio/mpeg', buffer: frames })
  await expect(source.getByRole('button', { name: 'Continue listening' })).toBeVisible()
  await expect(source.getByRole('button', { name: 'Continue reading' })).toHaveCount(0)
  await expect(source.getByRole('button', { name: /^Attach to:/ })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('audio-mobile.png') })
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: /The Tainted Cup/ }).first().click()
  await expect(source.getByRole('button', { name: 'Continue listening' })).toBeVisible()
  await page.locator('.book-notes > summary').click()
  await expect(page.getByLabel('Private note')).toHaveValue('Return to chapter twelve.')
  await page.setViewportSize({ width: 320, height: 568 })
  await page.evaluate(() => { document.documentElement.dataset.typeScale = 'x-large' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('audio-large-type.png') })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.evaluate(() => { document.documentElement.dataset.typeScale = 'standard' })
  await page.screenshot({ path: testInfo.outputPath('audio-desktop.png') })
  expect(errors).toEqual([])
})
