// Installed Chromium extension against synthetic, offline shelf fixtures. No account data.
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import './build.mjs';
const require = createRequire(new URL('../mobile/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const extension = fileURLToPath(new URL('./dist/chromium', import.meta.url));
const profile = await mkdtemp(join(tmpdir(), 'wovenleaf-libby-companion-'));
const tile = (id, label, format = 'audiobook', style = '') => `<article class="title-tile data-tile-class_loan data-title_${id} data-title-tile-format_${format}" style="${style}"><b class="title-tile-title">Book ${id}</b><span class="title-tile-author">A. Reader</span><span class="download">Downloaded 100%</span><a class="title-tile-journey-percent" href="/shelf/journey/${id}"><span data-access="visual">${label}</span></a></article>`;
let context;
try {
  context = await chromium.launchPersistentContext(profile, { headless: true, channel: 'chromium', args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`] });
  await context.route('https://libbyapp.com/**', route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><body>${tile('111','0%')}${tile('222','37,5%','ebook')}${tile('333','95%','audiobook','display:none')}${tile('444','101%')}${tile('555','Unknown')}${tile('666','28%','magazine')}${tile('777','12%')}${tile('777','55%')}<div id="unrelated">Never capture this</div></body>` }));
  const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
  const page = await context.newPage(); await page.goto('https://libbyapp.com/shelf');
  const snapshot = () => worker.evaluate(async () => (await chrome.storage.session.get('snapshot')).snapshot);
  await page.waitForTimeout(800); assert.equal(await snapshot(), undefined);
  await worker.evaluate(() => chrome.storage.local.set({ enabled: true }));
  await page.locator('#unrelated').evaluate(el => el.textContent = 'Trigger after opt-in');
  await expect.poll(async () => (await snapshot())?.observations.length).toBe(2);
  const first = await snapshot();
  assert.deepEqual(first.observations, [{ titleId:'111',format:'audiobook',title:'Book 111',author:'A. Reader',percent:0 }, {titleId:'222',format:'ebook',title:'Book 222',author:'A. Reader',percent:37.5}]);
  assert.equal(await page.evaluate(() => typeof globalThis.readWovenleafShelf), 'undefined');
  await page.locator('.data-title_111 [data-access="visual"]').evaluate(el => el.textContent = '42%');
  await expect.poll(async () => (await snapshot())?.observations[0].percent).toBe(42);
  await page.evaluate(() => history.pushState({}, '', '/open/book'));
  await page.locator('.data-title_111 [data-access="visual"]').evaluate(el => el.textContent = '66%');
  await page.waitForTimeout(800); assert.equal((await snapshot()).observations[0].percent, 42);
  await page.evaluate(() => history.pushState({}, '', '/shelf/loans'));
  await page.locator('#unrelated').evaluate(el => el.textContent = 'Back on the shelf');
  await expect.poll(async () => (await snapshot())?.observations[0].percent).toBe(66);
  const current = await snapshot();
  const validation = await worker.evaluate(value => ({ valid: WovenleafLibby.valid(value), extra: WovenleafLibby.valid({...value, token:'must reject'}), bool: WovenleafLibby.valid({...value, observations:[{...value.observations[0],percent:true}]}), duplicates: WovenleafLibby.valid({...value, observations:[value.observations[0],value.observations[0]]}) }), current);
  assert.deepEqual(validation, {valid:true,extra:false,bool:false,duplicates:false});
  const popup = await context.newPage();
  await popup.goto(`chrome-extension://${new URL(worker.url()).host}/popup.html`);
  await expect(popup.locator('#titles li')).toHaveCount(2);
  const downloadEvent = popup.waitForEvent('download'); await popup.getByRole('button',{name:'Save progress file'}).click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(),'wovenleaf-libby.json');
  assert.deepEqual(JSON.parse(await readFile(await download.path(),'utf8')),current);
  await popup.evaluate(() => { navigator.share = async data => { globalThis.shared = data; }; navigator.canShare = () => false; });
  await popup.getByRole('button',{name:'Send to Wovenleaf',exact:true}).click();
  assert.equal(await popup.evaluate(() => globalThis.shared.text), 'Wovenleaf Libby progress\n' + JSON.stringify(current));
  await popup.getByRole('checkbox').uncheck();
  await expect.poll(snapshot).toBeUndefined();
  console.log('PASS: opt-in, installed MV3 capture, zero/fractional progress, duplicates/hidden/invalid labels, SPA changes, isolated world, validation, popup export, share fallback, and erase on pause.');
} finally { await context?.close(); await rm(profile,{recursive:true,force:true}); }
